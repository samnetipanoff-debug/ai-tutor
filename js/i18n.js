const SUPPORTED_LANGUAGES = ["ru", "en", "de", "sr", "es", "fr"];
const FALLBACK_LANGUAGE = "en";

/**
 * Возвращает объект переводов для языка.
 */
export function getUITranslations(language) {
  return UI[language] || UI[FALLBACK_LANGUAGE];
}

/**
 * Получить строку по пути "onboarding.step_interface_title".
 * Поддерживает подстановку {var}.
 */
export function t(path, vars = null, language = FALLBACK_LANGUAGE) {
  const dict = getUITranslations(language);
  const parts = path.split(".");
  let value = dict;

  for (const part of parts) {
    if (value && typeof value === "object" && part in value) {
      value = value[part];
    } else {
      return path;
    }
  }

  if (typeof value !== "string") return path;

  if (vars) {
    return value.replace(/\{(\w+)\}/g, (_, key) =>
      key in vars ? String(vars[key]) : `{${key}}`,
    );
  }

  return value;
}

export function isSupportedLanguage(code) {
  return SUPPORTED_LANGUAGES.includes(code);
}

export function getSupportedLanguages() {
  return [...SUPPORTED_LANGUAGES];
}

export default UI;
